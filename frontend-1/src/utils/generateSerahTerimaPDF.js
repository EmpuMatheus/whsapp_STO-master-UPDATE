import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export async function generateSerahTerimaPDF({ tags, summary, verifier }) {
  console.log("[SerahTerimaPDF] Generating PDF with", tags?.length, "tags");
  if (!tags || tags.length === 0) {
    console.warn("[SerahTerimaPDF] No tags to generate");
    return;
  }

  try {
    const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });

    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();
    const ml = 8;
    const mr = 8;

    const today = new Date();
    const dateStr = today.toLocaleDateString("id-ID", {
      day: "2-digit",
      month: "short",
      year: "numeric"
    });
    const timeStr = today.toLocaleTimeString("id-ID", {
      hour: "2-digit",
      minute: "2-digit"
    });

    /* ==================================================
       FOOTER — three columns
    ================================================== */
    const drawFooter = (docRef, pageNum, totalPages) => {
      const fy = pageHeight - 10;

      docRef.setDrawColor(180);
      docRef.setLineWidth(0.3);
      docRef.line(ml, fy - 3, pageWidth - mr, fy - 3);

      docRef.setFont("times", "normal");
      docRef.setFontSize(7);
      docRef.setTextColor(100);

      docRef.text("Generated by STO BBP System", ml, fy);
      docRef.text(`Total Tag : ${tags.length}`, ml, fy + 3.5);

      docRef.text(`Tanggal Cetak : ${dateStr} ${timeStr}`, pageWidth / 2, fy, { align: "center" });

      docRef.text(`Halaman ${pageNum} / ${totalPages}`, pageWidth - mr, fy, { align: "right" });
    };

    /* ==================================================
       HEADER DOKUMEN
    ================================================== */
    let y = 12;

    doc.setFont("times", "bold");
    doc.setFontSize(14);
    doc.setTextColor(0, 51, 102);
    doc.text("BERITA ACARA", pageWidth / 2, y, { align: "center" }); y += 6;

    doc.setFontSize(13);
    doc.text("SERAH TERIMA TAG STOCK OPNAME", pageWidth / 2, y, { align: "center" }); y += 6;

    doc.setFontSize(10);
    doc.setFont("times", "normal");
    doc.setTextColor(80);
    doc.text("PT. Bahana Bhumiphala Persada", pageWidth / 2, y, { align: "center" }); y += 6;

    doc.setDrawColor(0, 51, 102);
    doc.setLineWidth(0.6);
    doc.line(ml, y, pageWidth - mr, y); y += 4;

    /* ==================================================
       ISI BERITA ACARA
    ================================================== */
    doc.setFont("times", "normal");
    doc.setFontSize(9);
    doc.setTextColor(40);
    doc.text("Pada hari ini telah dilakukan serah terima Tag Stock Opname sebagai berikut:", ml, y); y += 5.5;

    const c1 = ml;
    const c2 = ml + 40;

    doc.setFont("times", "bold");
    doc.text("Pihak Pertama", c1, y);
    doc.setFont("times", "normal");
    doc.text(": Administrator", c2, y); y += 4.5;

    doc.setFont("times", "bold");
    doc.text("Pihak Kedua", c1, y);
    doc.setFont("times", "normal");
    doc.text(`: ${verifier?.name || "-"}`, c2, y); y += 4.5;

    const uniqueCounters = [...new Set(tags.map(t => t.counter_name).filter(Boolean))].join(", ");
    const uniqueWhs = [...new Set(tags.map(t => t.whs_code).filter(Boolean))].join(", ");
    const uniqueLoc = [...new Set(tags.map(t => t.location_name).filter(Boolean))].join(", ");

    doc.setFont("times", "bold");
    doc.text("Counter", c1, y);
    doc.setFont("times", "normal");
    doc.text(`: ${uniqueCounters || "-"}`, c2, y); y += 4.5;

    doc.setFont("times", "bold");
    doc.text("Jumlah Tag", c1, y);
    doc.setFont("times", "normal");
    doc.text(`: ${tags.length} Tag`, c2, y); y += 4.5;

    doc.setFont("times", "bold");
    doc.text("Warehouse", c1, y);
    doc.setFont("times", "normal");
    doc.text(`: ${uniqueWhs || "-"}`, c2, y); y += 4.5;

    doc.setFont("times", "bold");
    doc.text("Location", c1, y);
    doc.setFont("times", "normal");
    doc.text(`: ${uniqueLoc || "-"}`, c2, y); y += 4.5;

    y += 2;
    doc.text("Tujuan: Pelaksanaan Stock Opname.", ml, y); y += 5;

    doc.setDrawColor(0, 51, 102);
    doc.setLineWidth(0.4);
    doc.line(ml, y, pageWidth - mr, y); y += 4;

    /* ==================================================
       TABEL DETAIL TAG — A4 Landscape
       Overflow: linebreak — wrap text otomatis
    ================================================== */
    console.log("[SerahTerimaPDF] Rendering table at y=", y);

    const cols = ["No","Seq","Tag QR","Whs","Item Code","Description","Detail Location","Location","Counter","Verificator","UOM","Qty","1st Count","Recount","Status","Remark"];
    const colW = [6, 7, 26, 12, 20, 46, 30, 20, 18, 18, 8, 10, 12, 12, 16, 20];

    const bodyData = tags.map((t, i) => [
      i + 1,
      t.seq ?? "-",
      t.tag_qr,
      t.whs_code,
      t.item_code,
      (t.description || "-"),
      (t.location_detail || "-"),
      t.location_name || "-",
      t.counter_name || "-",
      t.verificator_name || "-",
      t.uom || "-",
      t.qty_pcs != null ? t.qty_pcs : "-",
      t.first_count_pcs != null ? t.first_count_pcs : "-",
      t.recount_pcs != null ? t.recount_pcs : "-",
      t.status || "-",
      (t.remark || "-")
    ]);

    autoTable(doc, {
      startY: y,
      head: [cols],
      body: bodyData,
      theme: "grid",
      margin: { left: ml, right: mr },
      styles: {
        font: "times",
        fontSize: 7,
        cellPadding: 1,
        lineColor: [80, 80, 80],
        lineWidth: 0.15,
        textColor: 30,
        overflow: "linebreak",
        valign: "middle"
      },
      headStyles: {
        font: "times",
        fontStyle: "bold",
        fontSize: 8,
        fillColor: [0, 51, 102],
        textColor: 255,
        halign: "center",
        valign: "middle"
      },
      columnStyles: {
        0: { cellWidth: colW[0], halign: "center" },
        1: { cellWidth: colW[1], halign: "center" },
        2: { cellWidth: colW[2], halign: "center" },
        3: { cellWidth: colW[3], halign: "center" },
        4: { cellWidth: colW[4], halign: "center" },
        5: { cellWidth: colW[5] },
        6: { cellWidth: colW[6] },
        7: { cellWidth: colW[7] },
        8: { cellWidth: colW[8] },
        9: { cellWidth: colW[9] },
        10: { cellWidth: colW[10], halign: "center" },
        11: { cellWidth: colW[11], halign: "center" },
        12: { cellWidth: colW[12], halign: "center" },
        13: { cellWidth: colW[13], halign: "center" },
        14: { cellWidth: colW[14], halign: "center" },
        15: { cellWidth: colW[15] }
      },
      didDrawPage: () => {
        const pg = doc.getNumberOfPages();
        drawFooter(doc, pg, "{total}");
      }
    });

    const finalTableY = doc.lastAutoTable.finalY || y;
    let ry = finalTableY + 5;
    console.log("[SerahTerimaPDF] Table done, finalY=", finalTableY);

    /* ==================================================
       RINGKASAN
    ================================================== */
    if (ry > pageHeight - 35) {
      doc.addPage();
      ry = 12;
    }

    doc.setDrawColor(0);
    doc.setLineWidth(0.3);
    doc.line(ml, ry, pageWidth - mr, ry); ry += 4;

    doc.setFont("times", "bold");
    doc.setFontSize(9);
    doc.setTextColor(0, 51, 102);
    doc.text("RINGKASAN", ml, ry); ry += 5;

    doc.setFont("times", "normal");
    doc.setFontSize(9);
    doc.setTextColor(40);

    const sumRows = [
      ["Total Tag", summary?.total ?? 0],
      ["Open", summary?.open ?? 0],
      ["Completed", summary?.completed ?? 0],
      ["Approval Success", summary?.approvalSuccess ?? 0],
      ["Recount", summary?.recount ?? 0],
      ["Minus", summary?.minus ?? 0],
      ["Over", summary?.over ?? 0]
    ];

    const half = Math.ceil(sumRows.length / 2);
    for (let i = 0; i < half; i++) {
      const left = sumRows[i];
      doc.setFont("times", "normal");
      doc.text(left[0], ml + 10, ry);
      doc.setFont("times", "bold");
      doc.text(`: ${left[1]}`, ml + 45, ry);

      const rightIdx = i + half;
      if (rightIdx < sumRows.length) {
        const right = sumRows[rightIdx];
        doc.setFont("times", "normal");
        doc.text(right[0], ml + 90, ry);
        doc.setFont("times", "bold");
        doc.text(`: ${right[1]}`, ml + 130, ry);
      }
      ry += 4.5;
    }

    ry += 5;

    /* ==================================================
       TANDA TANGAN
    ================================================== */
    if (ry > pageHeight - 50) {
      doc.addPage();
      ry = 12;
    }

    doc.setDrawColor(0);
    doc.setLineWidth(0.5);
    doc.line(ml, ry, pageWidth - mr, ry); ry += 4;

    doc.setFont("times", "bold");
    doc.setFontSize(10);
    doc.setTextColor(0, 51, 102);
    doc.text("TANDA TANGAN", pageWidth / 2, ry, { align: "center" }); ry += 7;

    const sigCol = (pageWidth - ml - mr) / 3;
    const sigLeft = ml;
    const sigMid = ml + sigCol;
    const sigRight = ml + sigCol * 2;

    const sigItems = [
      { title: "Diserahkan Oleh", role: "Administrator", x: sigLeft + sigCol / 2 },
      { title: "Diterima Oleh", role: verifier?.name || "-", x: sigMid + sigCol / 2 },
      { title: "Mengetahui", role: "Supervisor", x: sigRight + sigCol / 2 }
    ];

    doc.setFont("times", "normal");
    doc.setFontSize(9.5);
    doc.setTextColor(40);

    for (const si of sigItems) {
      doc.setFont("times", "bold");
      doc.text(si.title, si.x, ry, { align: "center" });
      doc.setFont("times", "normal");
      doc.text(si.role, si.x, ry + 6, { align: "center" });
      doc.text("( ................. )", si.x, ry + 20, { align: "center" });
      doc.text("Tanggal: ................", si.x, ry + 26, { align: "center" });
    }

    /* ==================================================
       FIX PAGE NUMBERS
    ================================================== */
    const pgCount = doc.getNumberOfPages();
    for (let p = 1; p <= pgCount; p++) {
      doc.setPage(p);
      drawFooter(doc, p, pgCount);
    }

    const filename = `BERITA_ACARA_SERAH_TERIMA_${(verifier?.name || "Unknown").replace(/\s+/g, "_")}_${today.toISOString().slice(0, 10)}.pdf`;
    console.log("[SerahTerimaPDF] Saving PDF:", filename);
    doc.save(filename);
    console.log("[SerahTerimaPDF] PDF generated successfully");

  } catch (err) {
    console.error("[SerahTerimaPDF] ERROR:", err);
    throw err;
  }
}
